package com.example.model

enum class ModeUnlockRule {
  ALWAYS_UNLOCKED,
  WINS_REQUIRED,
  CATS_SAVED_REQUIRED,
  ENDLESS_RECORD_REQUIRED,
  ACHIEVEMENTS_REQUIRED,
  ITEMS_FOUND_REQUIRED,
  GHOSTS_SCARED_REQUIRED
}

data class GameModeDef(
  val id: String,
  val number: Int,
  val name: String,
  val emoji: String,
  val description: String,
  val objectiveText: String,
  val unlockDescription: String,
  val unlockRule: ModeUnlockRule,
  val unlockTarget: Int,
  val goalCats: Int = 10, // -1 means infinite / endless
  val ghostCount: Int = 1,
  val ghostSpeedMult: Float = 1.0f,
  val heroSpeedMult: Float = 1.0f,
  val heroLives: Int = 3,
  val timeLimitSec: Float = 0f, // 0f = no time limit
  val startingCatsOnMap: Int = 1,
  val powerUpSpawnMult: Float = 1.0f,
  val isEndless: Boolean = false,
  val infiniteTurbo: Boolean = false,
  val infiniteSonic: Boolean = false,
  val isDarknessMode: Boolean = false,
  val isGodTrialMode: Boolean = false,
  val isBotsMode: Boolean = false,
  val botCount: Int = 0,
  val arenaThemeOverride: ArenaTheme? = null
) {
  fun isUnlocked(
    wins: Int,
    totalCats: Int,
    bestEndless: Int,
    achievementsCount: Int,
    discoveredItemsCount: Int,
    ghostsScared: Int
  ): Boolean {
    return when (unlockRule) {
      ModeUnlockRule.ALWAYS_UNLOCKED -> true
      ModeUnlockRule.WINS_REQUIRED -> wins >= unlockTarget
      ModeUnlockRule.CATS_SAVED_REQUIRED -> totalCats >= unlockTarget
      ModeUnlockRule.ENDLESS_RECORD_REQUIRED -> bestEndless >= unlockTarget
      ModeUnlockRule.ACHIEVEMENTS_REQUIRED -> achievementsCount >= unlockTarget
      ModeUnlockRule.ITEMS_FOUND_REQUIRED -> discoveredItemsCount >= unlockTarget
      ModeUnlockRule.GHOSTS_SCARED_REQUIRED -> ghostsScared >= unlockTarget
    }
  }

  fun currentProgress(
    wins: Int,
    totalCats: Int,
    bestEndless: Int,
    achievementsCount: Int,
    discoveredItemsCount: Int,
    ghostsScared: Int
  ): Int {
    return when (unlockRule) {
      ModeUnlockRule.ALWAYS_UNLOCKED -> 1
      ModeUnlockRule.WINS_REQUIRED -> wins
      ModeUnlockRule.CATS_SAVED_REQUIRED -> totalCats
      ModeUnlockRule.ENDLESS_RECORD_REQUIRED -> bestEndless
      ModeUnlockRule.ACHIEVEMENTS_REQUIRED -> achievementsCount
      ModeUnlockRule.ITEMS_FOUND_REQUIRED -> discoveredItemsCount
      ModeUnlockRule.GHOSTS_SCARED_REQUIRED -> ghostsScared
    }.coerceAtMost(unlockTarget.coerceAtLeast(1))
  }
}

